const { Client } = require('ssh2');
const path = require('path');

require('dotenv').config({ path: path.resolve(__dirname, '../.env') });

const host = process.env.DEPLOY_HOST;
const username = process.env.DEPLOY_USER;
const password = process.env.DEPLOY_PASS;

const config = {
  host,
  port: parseInt(process.env.DEPLOY_PORT || '22'),
  username,
  password,
  readyTimeout: 60000
};

const conn = new Client();

conn.on('ready', () => {
  const cmd = `node -e "const c = require('./Sniper-Car-Care---POS-System/backend/controllers/analyticsController'); console.log('DAILY_SUMMARY:', c.getDailyBusinessSummary.toString().substring(0, 300)); console.log('DASHBOARD:', c.getDashboardAnalytics.toString().substring(0, 300));"`;
  conn.exec(cmd, (err, stream) => {
    if (err) {
      console.error(err);
      conn.end();
      return;
    }
    stream.on('close', () => {
      conn.end();
    }).on('data', (data) => {
      process.stdout.write(data);
    }).stderr.on('data', (data) => {
      process.stderr.write(data);
    });
  });
}).connect(config);
